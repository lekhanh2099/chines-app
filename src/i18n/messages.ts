import type { AppLocale } from "./config";

async function loadViMessages() {
 const [
  common,
  shell,
  auth,
  inspector,
  settings,
  notes,
  noteTabs,
  noteEditor,
  dictionary,
  reader,
  readerStudy,
  readerDocument,
  dailyReading,
  dailyReadingV2,
  readerDataQuality,
  humanities,
  humanitiesPractice,
  aiSettings,
  aiConversation,
  aiConversationSettings,
  aiLookupSettings,
  aiUsage,
  apiKeySetup,
  learningLoop,
 ] = await Promise.all([
  import("../../messages/vi/common.json"),
  import("../../messages/vi/shell.json"),
  import("../../messages/vi/auth.json"),
  import("../../messages/vi/inspector.json"),
  import("../../messages/vi/settings.json"),
  import("../../messages/vi/notes.json"),
  import("../../messages/vi/note-tabs.json"),
  import("../../messages/vi/note-editor.json"),
  import("../../messages/vi/dictionary.json"),
  import("../../messages/vi/reader.json"),
  import("../../messages/vi/reader-study.json"),
  import("../../messages/vi/reader-document.json"),
  import("../../messages/vi/daily-reading.json"),
  import("../../messages/vi/daily-reading-v2.json"),
  import("../../messages/vi/reader-data-quality.json"),
  import("../../messages/vi/humanities.json"),
  import("../../messages/vi/humanities-practice.json"),
  import("../../messages/vi/ai-settings.json"),
  import("../../messages/vi/ai-conversation.json"),
  import("../../messages/vi/ai-conversation-settings.json"),
  import("../../messages/vi/ai-lookup-settings.json"),
  import("../../messages/vi/ai-usage.json"),
  import("../../messages/vi/api-key-setup.json"),
  import("../../messages/vi/learning-loop.json"),
 ]);

 return {
  Common: common.default,
  Shell: shell.default,
  Auth: auth.default,
  Inspector: inspector.default,
  Settings: settings.default,
  Notes: { ...notes.default, tabs: noteTabs.default, editor: noteEditor.default },
  Dictionary: dictionary.default,
  Reader: { ...reader.default, study: readerStudy.default, document: readerDocument.default },
  DailyReading: { ...dailyReading.default, v2: dailyReadingV2.default },
  ReaderDataQuality: readerDataQuality.default,
  Humanities: humanities.default,
  HumanitiesPractice: humanitiesPractice.default,
  AiSettings: aiSettings.default,
  AiConversation: aiConversation.default,
  AiConversationSettings: aiConversationSettings.default,
  AiLookupSettings: aiLookupSettings.default,
  AiUsage: aiUsage.default,
  ApiKeySetup: apiKeySetup.default,
  LearningLoop: learningLoop.default,
 };
}

export type AppMessages = Awaited<ReturnType<typeof loadViMessages>>;

